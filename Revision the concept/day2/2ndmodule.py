## variables and datatypes

# VARIABlES are containers for storing data values. In Python, variables do not need to be declared with any particular type and can even change type after they have been set.


a = 13
print(a)
print(type(a))

b = "Pinki"
print(b)
print(type(b))

c = 3.14
print(c)
print(type(c))

d = True 
print(d)
print(type(d))

e= None
print(e)
print(type(e))


